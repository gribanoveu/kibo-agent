fn main() {
    // The Windows manifest — Common Controls v6, which the dialogs and the
    // webview need — is linked here rather than by tauri-build: its resource
    // reaches only the app's binary, and the test binary, without it, does
    // not start (`STATUS_ENTRYPOINT_NOT_FOUND`). A link argument reaches every
    // binary of the package, tests included.
    let windows = tauri_build::WindowsAttributes::new_without_app_manifest();
    // Declared, the app's commands are refused in a window whose capability
    // does not allow them; undeclared, every window may call every one.
    let commands: &'static [&'static str] = Box::leak(commands().into_boxed_slice());
    main_window_permission(commands);
    let manifest = tauri_build::AppManifest::new().commands(commands);
    // As `tauri_build::build()` ends on a failure.
    if let Err(error) =
        tauri_build::try_build(tauri_build::Attributes::new().windows_attributes(windows).app_manifest(manifest))
    {
        println!("{error:#}");
        std::process::exit(1);
    }

    let target = (std::env::var("CARGO_CFG_TARGET_OS"), std::env::var("CARGO_CFG_TARGET_ENV"));
    if matches!(target, (Ok(os), Ok(env)) if os == "windows" && env == "msvc") {
        let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("windows-app-manifest.xml");
        println!("cargo:rerun-if-changed={}", manifest.display());
        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest.display());
    }
}

/// The app's commands, read from `generate_handler!` in `src/lib.rs` — the one
/// list of them, so a command registered there cannot be missing here.
fn commands() -> Vec<&'static str> {
    println!("cargo:rerun-if-changed=src/lib.rs");
    let lib = std::fs::read_to_string("src/lib.rs").expect("src/lib.rs is readable");
    let handler = lib
        .split("generate_handler![")
        .nth(1)
        .and_then(|rest| rest.split(']').next())
        .expect("src/lib.rs registers its commands with generate_handler!");
    let names: Vec<&'static str> = handler
        .split(',')
        .filter_map(|path| path.trim().rsplit("::").next())
        .filter(|name| !name.is_empty())
        .map(|name| &*Box::leak(name.to_string().into_boxed_str()))
        .collect();
    assert!(names.len() > 100, "read {} commands from generate_handler!: its shape changed?", names.len());
    names
}

/// `permissions/main-window.toml`: one permission allowing every command,
/// which `capabilities/default.json` gives the main window. Generated rather
/// than written by hand so it cannot fall behind `generate_handler!`; written
/// only when it changes, since Tauri rebuilds on any change in `permissions/`.
fn main_window_permission(commands: &[&str]) {
    let list = commands.iter().map(|c| format!("  \"{c}\",\n")).collect::<String>();
    let toml = format!(
        "# Generated by build.rs from generate_handler! in src/lib.rs - DO NOT EDIT.\n\n\
         [[permission]]\n\
         identifier = \"main-window\"\n\
         description = \"Every command of the app: the main window drives all of it.\"\n\
         commands.allow = [\n{list}]\n"
    );
    let path = std::path::Path::new("permissions/main-window.toml");
    if std::fs::read_to_string(path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::create_dir_all("permissions").expect("permissions/ can be created");
        std::fs::write(path, toml).expect("permissions/main-window.toml can be written");
    }
}
